def get_issues_by_category(category: BenchmarkCategory | str) -> list[BenchmarkIssue]:
    """Filter benchmark issues by category."""
    cat_val = category.value if isinstance(category, BenchmarkCategory) else category
    return [issue for issue in BENCHMARK_DATASET if issue.category.value == cat_val]
